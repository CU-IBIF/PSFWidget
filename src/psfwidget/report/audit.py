"""The audit review report (QA-06).

A report of everything the audit trail records for a period, for the
periodic review GLP expects: counts by action and by user, then every
exclusion and inclusion, event, approval, import, and database upgrade, and
finally the complete list of entries. It is signed like any other report
(``psfwidget approve``).
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from datetime import UTC, datetime
from typing import Any

from psfwidget import __version__
from psfwidget.report import document as doc
from psfwidget.tracking.store import ResultsDatabase

SECTIONS = (
    ("Exclusions and inclusions", ("exclude", "include")),
    ("Events", ("event",)),
    ("Report approvals and rejections", ("report approved", "report rejected")),
    ("Imports and database upgrades", ("import", "schema migrated")),
)
DETAIL_LIMIT = 160


def _base(action: str) -> str:
    return action.removesuffix(" (imported)")


def _details(details: dict[str, Any]) -> str:
    text = ", ".join(f"{k}={v}" for k, v in details.items() if v not in (None, [], {}, ""))
    return text if len(text) <= DETAIL_LIMIT else text[: DETAIL_LIMIT - 1] + "…"


def _who(entry: dict[str, Any]) -> str:
    return str(entry["user"]) + (f" @ {entry['host']}" if entry.get("host") else "")


def _table(entries: Sequence[dict[str, Any]], caption: str) -> doc.Table:
    return doc.Table(
        ("Time (UTC)", "User @ computer", "Action", "Details"),
        tuple((e["utc"], _who(e), e["action"], _details(e["details"])) for e in entries),
        caption=caption,
    )


def build_audit_report(
    database: ResultsDatabase,
    *,
    since: datetime | None = None,
    until: datetime | None = None,
    branding: doc.Branding | None = None,
) -> doc.Report:
    """Build the audit review report of a results database for a period."""
    entries = database.audit_entries(since, until)
    period = (
        f"{since.date().isoformat() if since else 'start'} to "
        f"{until.date().isoformat() if until else 'now'}"
    )
    blocks: list[doc.Block] = [
        doc.Heading("Summary"),
        doc.KeyValues(
            (
                ("Database", str(database.path.resolve())),
                ("Period", period),
                ("Entries", str(len(entries))),
                ("Users", ", ".join(sorted({e["user"] for e in entries})) or "-"),
                ("Computers", ", ".join(sorted({e["host"] or "-" for e in entries})) or "-"),
            )
        ),
    ]
    by_action = Counter(e["action"] for e in entries)
    by_user = Counter(e["user"] for e in entries)
    if entries:
        blocks.append(
            doc.Table(
                ("Action", "Entries"),
                tuple((a, str(n)) for a, n in sorted(by_action.items())),
                frozenset({1}),
                caption="Entries by action.",
            )
        )
        blocks.append(
            doc.Table(
                ("User", "Entries"),
                tuple((u, str(n)) for u, n in sorted(by_user.items())),
                frozenset({1}),
                caption="Entries by user.",
            )
        )
    for title, actions in SECTIONS:
        selected = [e for e in entries if _base(e["action"]) in actions]
        blocks.append(doc.Heading(title))
        if selected:
            blocks.append(_table(selected, f"{len(selected)} entries."))
        else:
            blocks.append(doc.Paragraph("None in this period.", muted=True))
    blocks.append(doc.PageBreak())
    blocks.append(doc.Heading("All entries"))
    if entries:
        blocks.append(_table(entries, "Every audit entry in the period, oldest first."))
    else:
        blocks.append(doc.Paragraph("No audit entries in this period.", muted=True))
    blocks.append(doc.Heading("Review"))
    blocks.append(
        doc.Paragraph(
            "Review the entries above, in particular every exclusion (with its reason), "
            "event, and approval, then sign this report: psfwidget approve <this file> "
            f'--db {database.path.name} --meaning "audit trail reviewed". '
            f"Generated by PSFWidget {__version__}."
        )
    )
    return doc.Report(
        title="Audit trail review",
        subtitle=f"{database.path.name}, {period}",
        status=None,
        generated_utc=datetime.now(UTC).replace(microsecond=0),
        blocks=tuple(blocks),
        branding=branding or doc.Branding(),
    )
